#ifndef EXSIM_RESEARCH_RUN_ARTIFACTS_HPP
#define EXSIM_RESEARCH_RUN_ARTIFACTS_HPP

// On-disk run artifacts (contract: docs/RESEARCH_RUNNER.md, artifact schema 1).
//
// A run directory holds:
//   manifest.json     immutable run description, written before the first event
//   experiment.conf   the experiment file exactly as given
//   status.json       run state and wall-clock progress (rewritten atomically)
//   commands.journal  canonical command journal (sim::JournalWriter; exsim_replay reads it)
//   commands.jsonl    every engine command with its source
//   events.jsonl      every engine event, regenerated by an independent replay
//   lifecycle.jsonl   strategy order lifecycle with FIFO queue evidence
//   ledger.jsonl      strategy fills with running cash/position/P&L
//   markouts.jsonl    one row per fill and horizon (measured, unavailable, censored)
//   series.csv        sampled book/inventory/equity series
//   summary.json      end-of-run accounting and metrics (written last)
//
// Everything except status.json is a deterministic function of the manifest:
// re-running the same configuration and seed reproduces the files byte for
// byte. Writing happens only while the run is yielded (FlushRequired or after
// the end), never inside the simulated hot path.

#include "exsim/research/run_summary.hpp"
#include "exsim/research/simulation_core.hpp"

#include <chrono>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <memory>
#include <stdexcept>
#include <string>
#include <string_view>

namespace exsim::sim {
class JournalWriter;
}

namespace exsim::research {

inline constexpr std::uint32_t kArtifactSchemaVersion = 1;
inline constexpr std::string_view kManifestSchema = "exsim.research.manifest/1";
inline constexpr std::string_view kStatusSchema = "exsim.research.status/1";
inline constexpr std::string_view kRunnerBuildId = "exsim.research.runner/1";
inline constexpr std::string_view kEngineBuildId = "exsim.matching_engine/canonical_encoding=1";

// Every file a run directory may contain (overwrite only ever removes these).
inline constexpr std::string_view kRunArtifactFileNames[] = {
    "manifest.json",   "experiment.conf", "status.json",   "status.json.tmp", "commands.journal", "commands.jsonl",
    "events.jsonl",    "lifecycle.jsonl", "ledger.jsonl",  "markouts.jsonl",  "series.csv",       "summary.json",
};

struct BuildInfo {
    std::string engine_build_id{kEngineBuildId};
    std::string runner_build_id{kRunnerBuildId};
    std::string executable_fnv1a64 = "unavailable";  // hash of the running executable file
    std::string compiler;
};

// Build identifiers of this binary; hashes `executable_path` when readable.
[[nodiscard]] BuildInfo current_build_info(const std::string& executable_path);

class ArtifactError : public std::runtime_error {
public:
    using std::runtime_error::runtime_error;
};

// "<experiment name>-<first 12 hex digits of config hash>-seed<master seed>",
// name reduced to [A-Za-z0-9_.-]. Deterministic, so a rerun has the same id.
[[nodiscard]] std::string make_run_id(std::string_view experiment_name, std::uint64_t config_hash, std::uint64_t master_seed);

struct RunArtifactOptions {
    std::filesystem::path run_directory;
    std::string run_id;
    std::string parent_run_id;       // empty: no parent
    std::string config_source_text;  // verbatim experiment file (experiment.conf)
    BuildInfo build;
    bool overwrite = false;          // replace an earlier run's artifacts in run_directory
};

[[nodiscard]] std::string render_manifest_json(const SimulationCore& core, const StrategyIdentity& strategy,
                                               const RunArtifactOptions& options);

// Prepares an empty run directory: creates it, or with `overwrite` removes the
// known artifact files of an earlier run. Refuses a directory that holds
// anything else. Throws ArtifactError.
void prepare_run_directory(const std::filesystem::path& directory, bool overwrite);

// Writes `text` to `path` through a temporary file and rename. Throws ArtifactError.
void write_file_atomically(const std::filesystem::path& path, std::string_view text);

[[nodiscard]] std::string read_text_file(const std::filesystem::path& path);  // throws ArtifactError

class RunArtifactWriter {
public:
    RunArtifactWriter(const SimulationCore& core, StrategyIdentity strategy, RunArtifactOptions options);
    ~RunArtifactWriter();
    RunArtifactWriter(const RunArtifactWriter&) = delete;
    RunArtifactWriter& operator=(const RunArtifactWriter&) = delete;

    // Directory, manifest.json, experiment.conf, status.json (state queued),
    // and the record streams. Call before the first step.
    void begin();
    // Appends every buffered record to its file and clears the recorder.
    void drain(RunRecorder& recorder);
    // Rewrites status.json from the core's current state. `driver_active`:
    // the caller is between chunks of a run it keeps driving, so a core paused
    // by a step budget is reported as running.
    void write_status(bool driver_active = false);
    // Final drain, journal footer, replay check, summary.json, final status.
    void finish(RunRecorder& recorder);

    // True after finish() when the independent replay reproduced the online
    // event digest and count.
    [[nodiscard]] bool replay_verified() const noexcept { return replay_verified_; }
    [[nodiscard]] std::uint64_t replay_event_digest() const noexcept { return replay_event_digest_; }
    [[nodiscard]] const std::filesystem::path& run_directory() const noexcept { return options_.run_directory; }
    [[nodiscard]] const std::string& run_id() const noexcept { return options_.run_id; }

private:
    struct ReplayState;

    void write_command_records(const RunRecorder& recorder);
    void write_lifecycle_records(const RunRecorder& recorder);
    void write_fill_records(const RunRecorder& recorder);
    void write_markout_records(const RunRecorder& recorder);
    void write_series_samples(const RunRecorder& recorder);
    void check_streams();

    const SimulationCore& core_;
    StrategyIdentity strategy_;
    RunArtifactOptions options_;
    std::unique_ptr<sim::JournalWriter> journal_;
    std::unique_ptr<ReplayState> replay_;
    std::ofstream commands_jsonl_;
    std::ofstream events_jsonl_;
    std::ofstream lifecycle_jsonl_;
    std::ofstream ledger_jsonl_;
    std::ofstream markouts_jsonl_;
    std::ofstream series_csv_;
    std::string line_buffer_;
    std::chrono::system_clock::time_point wall_started_;
    std::chrono::steady_clock::time_point steady_started_;
    bool begun_ = false;
    bool finished_ = false;
    bool replay_verified_ = false;
    std::uint64_t replay_event_digest_ = 0;
    std::uint64_t commands_written_ = 0;
};

}  // namespace exsim::research

#endif
